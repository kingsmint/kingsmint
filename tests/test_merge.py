import datetime as dt
from decimal import Decimal

import pytest

from kingsmint.banks.common import Txn
from kingsmint.importer import txn_id
from kingsmint.merge import chunks, merge_file, merge_txn


def txn(flag="*", narration="Card", account="Expenses:Uncategorized", meta=""):
    return (f'2025-06-01 {flag} "Shop" "{narration}"\n  id: "km-1"\n{meta}  document: "a.pdf"\n'
            f"  Assets:Bank  -10.00 EUR\n  {account}\n")


BASE = txn("!")
RULED = txn("*", account="Expenses:Food")  # a new rule categorized it


def test_untouched_takes_the_new_rule():
    assert merge_txn(BASE, BASE, RULED) == (RULED, [])


def test_edit_survives_when_nothing_else_changed():
    mine = txn("!", "Museum annual pass")
    assert merge_txn(BASE, mine, BASE) == (mine, [])


def test_edit_and_rule_both_apply():
    mine = txn("!", "Museum annual pass", meta='  note: "for the family"\n').replace('"Museum annual pass"', '"Museum annual pass" #museum')
    text, conflicts = merge_txn(BASE, mine, RULED)
    assert conflicts == []
    assert text.startswith('2025-06-01 * "Shop" "Museum annual pass" #museum\n')  # flag from the rule, the rest from the user
    assert '  note: "for the family"\n' in text and "  Expenses:Food\n" in text


def test_both_change_postings_keeps_mine():
    mine = txn("!", account="Expenses:Fun")
    text, conflicts = merge_txn(BASE, mine, RULED)
    assert conflicts == ["postings"] and "Expenses:Fun" in text and text.startswith("2025-06-01 *")


def test_comments_stay_next_to_their_item():
    mine = txn("!", "Museum", meta="  ; after id and note\n").replace("  Assets:Bank  -10.00 EUR\n",
                                                                    "  Assets:Bank  -10.00 EUR ; own\n  ; after bank\n")
    text, _ = merge_txn(BASE, mine, RULED)
    assert "  ; after id and note\n" in text and text.index("; after bank") > text.index("Assets:Bank")
    assert "-10.00 EUR ; own\n" in text and "  Expenses:Food\n" in text  # a comment does not stop the rule


def test_merge_file_keeps_leading_comment_and_spacing():
    theirs = f"; generated by kingsmint\n\n2025-05-31 balance Assets:Bank 10.00 EUR\n\n{RULED}\n2025-06-30 balance Assets:Bank 0.00 EUR\n"
    kept = {"km-1": (None, BASE, "; annual pass\n", txn("!", "Museum"))}
    used = set()
    text, messages = merge_file(theirs, kept, used)
    assert used == {"km-1"} and messages == []
    assert f'\n\n; annual pass\n{txn("*", "Museum", account="Expenses:Food")}\n2025-06-30' in text


def test_unreadable_line_stops_before_anything_is_deleted():
    with pytest.raises(ValueError, match=":3:"):  # tree-sitter-beancount: no comment after a metadata value
        chunks('2025-06-01 open Assets:Bank\n  iban: "SK11"\n  until: 2025-01-01 ; why\n', "accounts.beancount")


def test_txn_id_numbers_equal_transactions():
    t = Txn(dt.date(2025, 6, 1), Decimal("-2.00"), "Cafe")
    assert txn_id("SK11", t, 0) != txn_id("SK11", t, 1)
    assert txn_id("SK11", t, 0) == txn_id("SK11", Txn(t.date, t.amount, "Café", vs="123", iban="SK22"), 0)  # a parser fix
    assert txn_id("SK11", t, 0) == txn_id("SK11", Txn(t.date, Decimal("-1.50"), "Cafe", fee=Decimal("-0.50")), 0)


def test_collect_keeps_the_edited_copy_of_a_duplicate(tmp_path):
    from kingsmint.merge import BASE as SNAPSHOT, collect
    head = "; generated by kingsmint\n\n"
    for folder in ("ledger/A", f"{SNAPSHOT}/ledger/A"):
        (tmp_path / folder).mkdir(parents=True)
        for name in ("1.beancount", "2.beancount"):
            (tmp_path / folder / name).write_text(head + BASE, encoding="utf-8")
    (tmp_path / "ledger/A/1.beancount").write_text(head + txn("!", "Museum"), encoding="utf-8")
    kept, _ = collect(tmp_path)
    assert '"Museum"' in kept["km-1"][3]  # whichever file is read last



def test_renamed_account_reaches_edited_postings():
    mine = txn("!", account="Expenses:Fun")
    theirs = BASE.replace("Assets:Bank", "Assets:Main")
    text, conflicts = merge_txn(BASE, mine, theirs)
    assert conflicts == [] and "  Assets:Main  -10.00 EUR\n" in text and "Expenses:Fun" in text and "Assets:Bank" not in text


def test_reset_takes_postings_and_flag_keeps_annotations():
    from kingsmint.merge import reset
    mine = txn("*", "Museum", account="Expenses:Fun", meta='  note: "kept"\n').replace("  Expenses:Fun\n", "  Expenses:Fun ; mine\n")
    text = reset(mine, BASE)
    assert text.startswith('2025-06-01 ! "Shop" "Museum"\n') and 'note: "kept"' in text
    assert "  Expenses:Uncategorized\n" in text and "Expenses:Fun" not in text
    assert "  ; mine\n" in text  # the comment of a posting that is gone stays, before the postings
