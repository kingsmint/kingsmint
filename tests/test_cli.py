import datetime as dt
import shutil
from pathlib import Path

import pytest

from kingsmint import cli


def test_doctor_fails_outside_a_ledger(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    with pytest.raises(SystemExit) as e:
        cli.doctor()
    assert e.value.code == 1
    assert "FAIL ledger files: missing main.beancount" in capsys.readouterr().out


def test_doctor_finds_unfilled_template(tmp_path, monkeypatch, capsys):
    shutil.copytree(Path(__file__).parent.parent / "template", tmp_path, dirs_exist_ok=True)
    monkeypatch.chdir(tmp_path)
    with pytest.raises(SystemExit):
        cli.doctor()
    out = capsys.readouterr().out
    assert "FAIL setup: TITLE, CURRENCY, LOCALE, LANGUAGE_CODE not replaced" in out
    assert "ok   ledger\n" in out  # the core accounts load without errors


def test_gaps():
    d = dt.date
    spans = [(d(2025, 1, 1), d(2025, 1, 31)), (d(2025, 2, 1), d(2025, 2, 28)), (d(2025, 4, 1), d(2025, 4, 30)),
             (d(2026, 1, 1), d(2026, 1, 1))]  # the last is an IBKR report: one date, no gap to it
    assert cli.gaps(spans) == [(d(2025, 3, 1), d(2025, 3, 31))]


def test_local_parser(tmp_path, monkeypatch, capsys):
    from kingsmint import banks
    (tmp_path / "banks").mkdir()
    (tmp_path / "banks" / "demo.py").write_text('"""Demo banka: PDF statements."""\nMARKER = "Demo banka"\n'
                                               'def parse_pdf(text):\n    return "parsed"\n', encoding="utf-8")
    monkeypatch.setattr(banks, "PARSERS", list(banks.PARSERS))
    monkeypatch.setattr(cli, "PARSERS", banks.PARSERS)
    banks.load_local(tmp_path / "banks")
    assert banks.PARSERS[0][0] == "Demo banka" and banks.PARSERS[0][1]("x") == "parsed"
    cli.banks()
    out = capsys.readouterr().out
    assert "local.demo  Demo banka: PDF statements." in out and "sk.vub  VÚB banka" in out and "intl.ibkr" in out


def test_upgrade(tmp_path, monkeypatch, capsys):
    log = tmp_path / "CHANGELOG.md"
    log.write_text("# Changelog\n\n## Unreleased\n\n### Ledger\n\n- not yet\n\n## 0.3.0\n\n- user note\n\n### Ledger\n\n"
                   "- add rule C\n\n## 0.2.0\n\n- no ledger change\n\n## 0.1.1\n\n### Ledger\n\n- add rule B\n\n"
                   "### Other\n\n- not ledger\n\n## 0.1.0\n\n### Ledger\n\n- old\n", encoding="utf-8")
    monkeypatch.setattr(cli, "CHANGELOG", log)
    monkeypatch.chdir(tmp_path)
    cli.upgrade([])  # no .kingsmint-version: a ledger from 0.1.0
    out = capsys.readouterr().out
    assert out.index("- add rule B") < out.index("- add rule C")  # oldest first
    assert "not yet" not in out and "not ledger" not in out and "- old" not in out and "0.2.0" not in out
    cli.upgrade(["--done"])
    assert (tmp_path / ".kingsmint-version").read_text() == "0.3.0\n"
    cli.upgrade([])
    assert "nothing to change" in capsys.readouterr().out.splitlines()[-1]


TXN = '{date} * "Shop" "Card"\n  id: "km-000000000001"\n  Assets:Me:Bank:Current  -10.00 EUR\n  Expenses:Uncategorized\n'


def ledger_with(tmp_path, monkeypatch, files):
    shutil.copytree(Path(__file__).parent.parent / "template", tmp_path, dirs_exist_ok=True)
    with (tmp_path / "accounts.beancount").open("a", encoding="utf-8") as f:
        f.write("2000-01-01 open Assets:Me:Bank:Current\n")
    for name, text in files.items():
        (tmp_path / name).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / name).write_text(text, encoding="utf-8")
    monkeypatch.chdir(tmp_path)


def test_check_finds_overlapping_statements(tmp_path, monkeypatch, capsys):
    ledger_with(tmp_path, monkeypatch, {"ledger/A/2025-03.beancount": TXN.format(date="2025-03-31"),
                                        "ledger/A/2025-Q1.beancount": TXN.format(date="2025-03-31")})
    with pytest.raises(SystemExit) as e:
        cli.check()
    assert e.value.code == 1
    assert ("FAIL ledger/A/2025-03.beancount and ledger/A/2025-Q1.beancount have the same 1 movements "
            "(2025-03-31 .. 2025-03-31)") in capsys.readouterr().out


def test_check_fails_until_orphans_are_resolved(tmp_path, monkeypatch, capsys):
    ledger_with(tmp_path, monkeypatch, {".kingsmint/orphans.beancount": "\n" + TXN.format(date="2025-03-31")})
    with pytest.raises(SystemExit) as e:
        cli.check()
    assert e.value.code == 1 and "FAIL .kingsmint/orphans.beancount: 1 entries" in capsys.readouterr().out
    (tmp_path / ".kingsmint/orphans.beancount").write_text("", encoding="utf-8")
    with pytest.raises(SystemExit) as e:
        cli.check()
    assert e.value.code == 0


def test_check_fails_on_a_line_reimport_cannot_read(tmp_path, monkeypatch, capsys):
    ledger_with(tmp_path, monkeypatch, {"ledger/A/2025-03.beancount": "; generated by kingsmint\n\n" +
                                        TXN.format(date="2025-03-31").replace('"km-000000000001"', '"km-000000000001" ; why')})
    with pytest.raises(SystemExit) as e:
        cli.check()
    assert e.value.code == 1 and "FAIL ledger/A/2025-03.beancount:4: cannot read this line" in capsys.readouterr().out


OLD = "; generated by kingsmint from a.pdf -- edits are lost on `kingsmint reimport`\n\n" + TXN.format(date="2025-03-31").replace('  id: "km-000000000001"\n', "")


def test_ledger_from_an_older_kingsmint(tmp_path, monkeypatch, capsys):
    ledger_with(tmp_path, monkeypatch, {"ledger/A/2025-03.beancount": OLD, "ledger/B/2025.beancount": OLD})  # B: IBKR, no ids
    with pytest.raises(SystemExit) as e:
        cli.check()
    assert e.value.code == 1 and "FAIL 1 files in ledger/ have no transaction ids" in capsys.readouterr().out
    calls = []
    monkeypatch.setattr(cli, "reimport", lambda: calls.append(1))
    cli.upgrade(["--done"])
    assert calls == [1] and "reimport: the statements in ledger/ get transaction ids" in capsys.readouterr().out
