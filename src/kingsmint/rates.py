"""Write prices.beancount in the current directory: month-end USD prices in EUR from the ECB reference rates (since 2013)."""

import csv
import io
import subprocess
import zipfile
from pathlib import Path

URL = "https://www.ecb.europa.eu/stats/eurofxref/eurofxref-hist.zip"


def main():
    # curl: uses the system certificates (Python may not find them)
    data = zipfile.ZipFile(io.BytesIO(subprocess.run(["curl", "-sfL", URL], capture_output=True, check=True).stdout))
    rows = csv.DictReader(io.TextIOWrapper(data.open("eurofxref-hist.csv"), "utf-8"))
    last = {}  # month -> (date, EUR per USD); rows are newest first, keep the latest day of each month
    for r in rows:
        if r["Date"] >= "2013" and r["USD"] not in ("", "N/A"):
            last.setdefault(r["Date"][:7], (r["Date"], 1 / float(r["USD"])))
    lines = [f"{d} price USD  {eur:.5f} EUR" for d, eur in sorted(last.values())]
    Path("prices.beancount").write_text("; generated by kingsmint rates (ECB)\n" + "\n".join(lines) + "\n", encoding="utf-8")
    print(len(lines), "prices")
